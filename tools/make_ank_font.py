def raster(path):
 rows=[0]*12
 for stroke in path.split(';'):
  points=[tuple(map(int,p.split(','))) for p in stroke.split()]
  if not points:continue
  for (x,y),(tx,ty) in zip(points,points[1:] or points):
   dx=abs(tx-x);dy=-abs(ty-y);sx=1 if x<tx else -1;sy=1 if y<ty else -1;error=dx+dy
   while True:
    assert 0<=x<7 and 0<=y<12
    rows[y]|=128>>x
    if (x,y)==(tx,ty):break
    e=2*error
    if e>=dy:error+=dy;x+=sx
    if e<=dx:error+=dx;y+=sy
 return rows
